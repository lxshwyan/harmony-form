  echo "HAR not found: ${HAR_FILE}" >&2
  exit 1
fi
tar -tzf "${HAR_FILE}" >/dev/null

PACKAGE_JSON="$(tar -xOzf "${HAR_FILE}" package/oh-package.json5)"
MODULE_JSON="$(tar -xOzf "${HAR_FILE}" package/src/main/module.json)"
ENTRY_DECLARATION="$(tar -xOzf "${HAR_FILE}" package/Index.d.ets)"
