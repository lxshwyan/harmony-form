FIELD_DECLARATION="$(tar -xOzf "${HAR_FILE}" package/src/main/ets/core/FormField.d.ets)"
INFERENCE_DECLARATION="$(tar -xOzf "${HAR_FILE}" package/src/main/ets/core/FormFieldInference.d.ets)"
PATH_DECLARATION="$(tar -xOzf "${HAR_FILE}" package/src/main/ets/core/FormPath.d.ets)"
RENDERER_DECLARATION="$(tar -xOzf "${HAR_FILE}" package/src/main/ets/core/FormRenderer.d.ets)"
SLOTS_DECLARATION="$(tar -xOzf "${HAR_FILE}" package/src/main/ets/core/FormSlots.d.ets)"
