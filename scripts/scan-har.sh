grep -Fq 'export type FormCondition' <<<"${FIELD_DECLARATION}"
grep -Fq 'export declare class FormSelectOption' <<<"${FIELD_DECLARATION}"
grep -Fq 'export type FormOptionsLoader = () => Promise<FormSelectOption[]>;' <<<"${FIELD_DECLARATION}"
grep -Fq 'export interface FormFieldUIOptions' <<<"${FIELD_DECLARATION}"
grep -Fq 'visibleWhen?: FormCondition;' <<<"${FIELD_DECLARATION}"
grep -Fq 'disabledWhen?: FormCondition;' <<<"${FIELD_DECLARATION}"
grep -Fq 'slots?: string[];' <<<"${FIELD_DECLARATION}"
