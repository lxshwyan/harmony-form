ARRAY_VIEW_DECLARATION="$(tar -xOzf "${HAR_FILE}" package/src/main/ets/components/HmFormArrayView.d.ets)"
THEME_DECLARATION="$(tar -xOzf "${HAR_FILE}" package/src/main/ets/theme/HmFormTheme.d.ets)"
CONTENTS="$(tar -tzf "${HAR_FILE}")"

grep -Eq '"name"[[:space:]]*:[[:space:]]*"@hmkit/form"' <<<"${PACKAGE_JSON}"
grep -Eq '"version"[[:space:]]*:[[:space:]]*"0\.1\.1"' <<<"${PACKAGE_JSON}"
grep -Eq '"@hmkit/validator"[[:space:]]*:[[:space:]]*"\^1\.0\.0"' <<<"${PACKAGE_JSON}"
grep -Eq '"debug"[[:space:]]*:[[:space:]]*false' <<<"${MODULE_JSON}"
grep -Fq '"2in1"' <<<"${MODULE_JSON}"
grep -Fq 'export { FormController, FormControllerOptions }' <<<"${ENTRY_DECLARATION}"
grep -Fq 'FormArrayController, FormArrayControllerOptions, FormArrayEntry, FormArrayIdentity, HmFormArrayItemContext' <<<"${ENTRY_DECLARATION}"
grep -Fq 'export { HmFormView }' <<<"${ENTRY_DECLARATION}"
grep -Fq 'export { HmFormArrayView }' <<<"${ENTRY_DECLARATION}"
grep -Fq 'export { HmFormTheme, HmFormThemeOptions }' <<<"${ENTRY_DECLARATION}"
grep -Fq 'FormFieldUIOptions, FormOptionsLoader, FormTextInputType, FormSelectOption' <<<"${ENTRY_DECLARATION}"
grep -Fq 'HmFormFieldRenderContext, HmFormFieldRenderer, HmFormRendererRegistry' <<<"${ENTRY_DECLARATION}"
grep -Fq 'export { HmFormSubmitSlotContext }' <<<"${ENTRY_DECLARATION}"
grep -Fq 'HmFormErrorSummaryContext, HmFormErrorSummaryItem, buildFormErrorSummaryItems' <<<"${ENTRY_DECLARATION}"
grep -Fq 'export { HmFormLayout, HmFormLayoutOptions }' <<<"${ENTRY_DECLARATION}"
grep -Fq 'FormSectionOptions, FormSectionSpec, FormStepOptions, FormStepSpec, FormStructureController' <<<"${ENTRY_DECLARATION}"
grep -Fq 'FormFieldInferenceOptions, FormFieldInferenceResult, inferFormFields' <<<"${ENTRY_DECLARATION}"
grep -Fq 'export { getFormValue, setFormValue }' <<<"${ENTRY_DECLARATION}"
grep -Fq 'export declare class FormController' <<<"${CONTROLLER_DECLARATION}"
grep -Fq 'validating: Record<string, boolean>;' <<<"${CONTROLLER_DECLARATION}"
grep -Fq 'optionValues: Record<string, FormSelectOption[]>;' <<<"${CONTROLLER_DECLARATION}"
grep -Fq 'optionsLoading: Record<string, boolean>;' <<<"${CONTROLLER_DECLARATION}"
grep -Fq 'optionErrors: Record<string, string>;' <<<"${CONTROLLER_DECLARATION}"
grep -Eq 'getFieldState\([^)]*: string\): FormFieldState;' <<<"${CONTROLLER_DECLARATION}"
grep -Eq 'getOptions\([^)]*: string\): FormSelectOption\[\];' <<<"${CONTROLLER_DECLARATION}"
grep -Fq 'loadAllOptions(): void;' <<<"${CONTROLLER_DECLARATION}"
