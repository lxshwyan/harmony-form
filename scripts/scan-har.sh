grep -Eq 'syncValues\([^)]*: Record<string, Object>\): boolean;' <<<"${CONTROLLER_DECLARATION}"
grep -Eq 'validateFields\([^)]*: string\[\]\): Promise<Record<string, string>>;' <<<"${CONTROLLER_DECLARATION}"
grep -Eq 'firstErrorName\([^)]*\?: string\[\]\): string \| undefined;' <<<"${CONTROLLER_DECLARATION}"
grep -Fq 'export type FormArrayIdentity = (value: Object, index: number) => string;' <<<"${ARRAY_DECLARATION}"
grep -Fq 'export interface FormArrayControllerOptions' <<<"${ARRAY_DECLARATION}"
grep -Fq 'export declare class FormArrayEntry' <<<"${ARRAY_DECLARATION}"
grep -Fq 'export declare class FormArrayController' <<<"${ARRAY_DECLARATION}"
grep -Fq 'entries: FormArrayEntry[];' <<<"${ARRAY_DECLARATION}"
grep -Fq 'getValues(): Object[];' <<<"${ARRAY_DECLARATION}"
grep -Eq 'insert\([^)]*: number, [^)]*: Object\): boolean;' <<<"${ARRAY_DECLARATION}"
grep -Eq 'move\([^)]*: number, [^)]*: number\): boolean;' <<<"${ARRAY_DECLARATION}"
grep -Eq 'syncValues\([^)]*: Object\[\]\): boolean;' <<<"${ARRAY_DECLARATION}"
grep -Fq 'export declare class HmFormArrayItemContext' <<<"${ARRAY_DECLARATION}"
grep -Fq 'readonly key: string;' <<<"${ARRAY_DECLARATION}"
grep -Fq 'moveUp(): void;' <<<"${ARRAY_DECLARATION}"
grep -Fq 'moveDown(): void;' <<<"${ARRAY_DECLARATION}"
grep -Fq 'static readonly TEXTAREA: string;' <<<"${FIELD_DECLARATION}"
grep -Fq 'static readonly SELECT: string;' <<<"${FIELD_DECLARATION}"
grep -Fq 'static readonly RADIO: string;' <<<"${FIELD_DECLARATION}"
grep -Fq 'static readonly CHECKBOX: string;' <<<"${FIELD_DECLARATION}"
grep -Fq 'static readonly SWITCH: string;' <<<"${FIELD_DECLARATION}"
grep -Fq 'static readonly DATE: string;' <<<"${FIELD_DECLARATION}"
grep -Eq 'static custom\([^)]*: string\): string;' <<<"${FIELD_DECLARATION}"
grep -Eq 'static isCustom\([^)]*: string\): boolean;' <<<"${FIELD_DECLARATION}"
grep -Fq 'export declare class FormFieldSlot' <<<"${FIELD_DECLARATION}"
grep -Fq 'static readonly PREFIX: string;' <<<"${FIELD_DECLARATION}"
