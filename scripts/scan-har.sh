grep -Eq 'usesSlot\([^)]*: string\): boolean;' <<<"${FIELD_DECLARATION}"
grep -Eq 'loadsOptions\(\): boolean;' <<<"${FIELD_DECLARATION}"
grep -Eq 'selectIndex\([^)]*: Object \| undefined, [^)]*\?: FormSelectOption\[\]\): number;' <<<"${FIELD_DECLARATION}"
grep -Eq 'selectValue\([^)]*: number, [^)]*\?: FormSelectOption\[\]\): string \| undefined;' <<<"${FIELD_DECLARATION}"
grep -Eq 'selectLabel\([^)]*: Object \| undefined, [^)]*\?: FormSelectOption\[\]\): string;' <<<"${FIELD_DECLARATION}"
grep -Eq 'checkboxValues\([^)]*: Object \| undefined, [^)]*\?: FormSelectOption\[\]\): string\[\];' <<<"${FIELD_DECLARATION}"
grep -Eq 'isOptionSelected\([^)]*: Object \| undefined, [^)]*: string, [^)]*\?: FormSelectOption\[\]\): boolean;' <<<"${FIELD_DECLARATION}"
grep -Eq 'toggleOptionValue\([^)]*: Object \| undefined, [^)]*: string, [^)]*: boolean, [^)]*\?: FormSelectOption\[\]\): string\[\];' <<<"${FIELD_DECLARATION}"
grep -Eq 'isVisible\([^)]*: Record<string, Object>\): boolean;' <<<"${FIELD_DECLARATION}"
grep -Eq 'isDisabled\([^)]*: Record<string, Object>\): boolean;' <<<"${FIELD_DECLARATION}"
grep -Eq 'dateModelValue\([^)]*: Date\): string;' <<<"${FIELD_DECLARATION}"
grep -Eq 'dateSelected\([^)]*: Object \| undefined\): Date;' <<<"${FIELD_DECLARATION}"
grep -Fq 'export interface FormFieldInferenceOptions' <<<"${INFERENCE_DECLARATION}"
grep -Fq 'export declare class FormFieldInferenceResult' <<<"${INFERENCE_DECLARATION}"
grep -Fq 'getInitialValues(): Record<string, Object>;' <<<"${INFERENCE_DECLARATION}"
grep -Fq 'export declare function inferFormFields' <<<"${INFERENCE_DECLARATION}"
grep -Eq 'export declare function getFormValue\([^)]*: Record<string, Object>, [^)]*: string\): Object \| undefined;' <<<"${PATH_DECLARATION}"
grep -Eq 'export declare function setFormValue\([^)]*: Record<string, Object>, [^)]*: string, [^)]*: Object \| undefined\): Record<string, Object>;' <<<"${PATH_DECLARATION}"
grep -Fq 'export declare class HmFormFieldRenderContext' <<<"${RENDERER_DECLARATION}"
grep -Fq 'export type HmFormFieldRenderer = WrappedBuilder<' <<<"${RENDERER_DECLARATION}"
grep -Fq 'export declare class HmFormRendererRegistry' <<<"${RENDERER_DECLARATION}"
grep -Eq 'register\([^)]*: string, [^)]*: HmFormFieldRenderer\): HmFormRendererRegistry;' <<<"${RENDERER_DECLARATION}"
grep -Eq 'matching\([^)]*: string\): HmFormFieldRenderer\[\];' <<<"${RENDERER_DECLARATION}"
grep -Eq 'assertFields\([^)]*: FormFieldSpec\[\]\): void;' <<<"${RENDERER_DECLARATION}"
grep -Fq 'export declare class HmFormSubmitSlotContext' <<<"${SLOTS_DECLARATION}"
grep -Fq 'readonly submitting: boolean;' <<<"${SLOTS_DECLARATION}"
grep -Fq 'readonly submit: () => void;' <<<"${SLOTS_DECLARATION}"
grep -Fq 'export declare class HmFormErrorSummaryItem' <<<"${ERRORS_DECLARATION}"
grep -Fq 'readonly sectionId: string;' <<<"${ERRORS_DECLARATION}"
grep -Fq 'readonly stepId: string;' <<<"${ERRORS_DECLARATION}"
grep -Fq 'location(): string;' <<<"${ERRORS_DECLARATION}"
grep -Fq 'export declare class HmFormErrorSummaryContext' <<<"${ERRORS_DECLARATION}"
grep -Fq 'readonly activate: (name: string) => void;' <<<"${ERRORS_DECLARATION}"
grep -Fq 'export declare function buildFormErrorSummaryItems' <<<"${ERRORS_DECLARATION}"
grep -Fq 'export interface HmFormLayoutOptions' <<<"${LAYOUT_DECLARATION}"
grep -Fq 'export declare class HmFormLayout' <<<"${LAYOUT_DECLARATION}"
grep -Fq 'readonly breakpoint: string;' <<<"${LAYOUT_DECLARATION}"
grep -Fq 'readonly columnGap: number;' <<<"${LAYOUT_DECLARATION}"
grep -Fq 'readonly rowGap: number;' <<<"${LAYOUT_DECLARATION}"
grep -Fq 'static responsive(): HmFormLayout;' <<<"${LAYOUT_DECLARATION}"
grep -Fq 'export interface FormSectionOptions' <<<"${STRUCTURE_DECLARATION}"
grep -Fq 'export declare class FormSectionSpec' <<<"${STRUCTURE_DECLARATION}"
grep -Fq 'export declare class FormStepSpec' <<<"${STRUCTURE_DECLARATION}"
grep -Fq 'export declare class FormStructureController' <<<"${STRUCTURE_DECLARATION}"
grep -Fq 'currentStepIndex: number;' <<<"${STRUCTURE_DECLARATION}"
grep -Fq 'expandedSections: Record<string, boolean>;' <<<"${STRUCTURE_DECLARATION}"
grep -Eq 'revealField\([^)]*: string\): boolean;' <<<"${STRUCTURE_DECLARATION}"
grep -Eq 'sectionForField\([^)]*: string\): FormSectionSpec \| undefined;' <<<"${STRUCTURE_DECLARATION}"
grep -Eq 'stepForField\([^)]*: string\): FormStepSpec \| undefined;' <<<"${STRUCTURE_DECLARATION}"
grep -Fq 'export declare struct HmFormView' <<<"${VIEW_DECLARATION}"
grep -Fq 'onSubmit: (values: Record<string, Object>) => void;' <<<"${VIEW_DECLARATION}"
grep -Fq 'onInvalid: (errors: Record<string, string>) => void;' <<<"${VIEW_DECLARATION}"
grep -Fq 'readonly renderers: HmFormRendererRegistry;' <<<"${VIEW_DECLARATION}"
grep -Fq 'readonly layout: HmFormLayout;' <<<"${VIEW_DECLARATION}"
grep -Fq 'readonly structure: FormStructureController | undefined;' <<<"${VIEW_DECLARATION}"
grep -Fq 'keepAlive?: boolean;' <<<"${FIELD_DECLARATION}"
grep -Fq 'readonly keepAlive: boolean;' <<<"${FIELD_DECLARATION}"
grep -Fq 'export declare class FormTextInputType' <<<"${FIELD_DECLARATION}"
grep -Fq 'inputType?: string;' <<<"${FIELD_DECLARATION}"
grep -Fq 'readonly inputType: string;' <<<"${FIELD_DECLARATION}"
grep -Fq 'readonly showErrorSummary: boolean;' <<<"${VIEW_DECLARATION}"
grep -Fq 'prefix: (context: HmFormFieldRenderContext) => void;' <<<"${VIEW_DECLARATION}"
grep -Fq 'suffix: (context: HmFormFieldRenderContext) => void;' <<<"${VIEW_DECLARATION}"
grep -Fq 'label: (context: HmFormFieldRenderContext) => void;' <<<"${VIEW_DECLARATION}"
grep -Fq 'help: (context: HmFormFieldRenderContext) => void;' <<<"${VIEW_DECLARATION}"
grep -Fq 'error: (context: HmFormFieldRenderContext) => void;' <<<"${VIEW_DECLARATION}"
grep -Fq 'submit: (context: HmFormSubmitSlotContext) => void;' <<<"${VIEW_DECLARATION}"
grep -Fq 'errorSummary: (context: HmFormErrorSummaryContext) => void;' <<<"${VIEW_DECLARATION}"
grep -Fq 'export declare struct HmFormArrayView' <<<"${ARRAY_VIEW_DECLARATION}"
grep -Fq 'readonly values: Object[];' <<<"${ARRAY_VIEW_DECLARATION}"
grep -Fq '$values: (values: Object[]) => void;' <<<"${ARRAY_VIEW_DECLARATION}"
grep -Fq 'item: (context: HmFormArrayItemContext) => void;' <<<"${ARRAY_VIEW_DECLARATION}"
grep -Fq 'export declare class HmFormTheme' <<<"${THEME_DECLARATION}"
grep -Fq 'static light(): HmFormTheme;' <<<"${THEME_DECLARATION}"
grep -Fq 'static dark(): HmFormTheme;' <<<"${THEME_DECLARATION}"
grep -Fxq 'package/README.md' <<<"${CONTENTS}"
grep -Fxq 'package/CHANGELOG.md' <<<"${CONTENTS}"
grep -Fxq 'package/LICENSE' <<<"${CONTENTS}"

if grep -Eq '(^|/)(entry|oh_modules|\.test|BuildProfile|build-profile\.json5|local\.properties|[^/]*(key|keystore|p12|cer|pem)[^/]*)($|/)' <<<"${CONTENTS}"; then
  echo "HAR contains forbidden development or credential-like paths:" >&2
  grep -E '(^|/)(entry|oh_modules|\.test|BuildProfile|build-profile\.json5|local\.properties|[^/]*(key|keystore|p12|cer|pem)[^/]*)($|/)' <<<"${CONTENTS}" >&2
  exit 1
fi

echo "HAR metadata, public declarations, release flag, and contents passed."
